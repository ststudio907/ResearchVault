// src/services/citation/bibliography-service.ts
//
// Vault-facing tail of the 3.2 C1 BibTeX pipeline: rebuilds
// `<project>/bibliography.bib` from the paper store. The serialization itself
// is pure and lives in `bibtex.ts`; this module owns the three unsafe bits:
// picking the write location, *not clobbering hand edits* (header-marker
// guard + ConfirmModal), and surviving an already-loaded plugin without a
// project root on disk.

import { normalizePath, TFile } from 'obsidian';
import type { ResearchVaultPlugin } from '../../core/plugin';
import { ConfirmModal } from '../../ui/modals/confirm-modal';
import { BIBTEX_GENERATED_HEADER, papersToBibtex } from './bibtex';

export interface BibliographyExportResult {
  /** Vault-relative path the bibliography was written to. */
  path: string;
  /** Number of entries exported. */
  count: number;
}

export class BibliographyService {
  constructor(private readonly plugin: ResearchVaultPlugin) {}

  /** Vault-relative path of a project's generated bibliography (no disk I/O). */
  bibliographyPath(projectId: string): string {
    const project = this.plugin.projectManager.getProjectById(projectId);
    if (!project) {
      throw new Error(`BibliographyService.bibliographyPath: project "${projectId}" not found.`);
    }
    return normalizePath(`${project.folderPath}/bibliography.bib`);
  }

  /**
   * Rebuild `<project>/bibliography.bib` from the current paper store.
   * Returns `null` when an existing hand-written file trips the overwrite
   * guard and the user declines — the caller should stay silent in that
   * case (the modal already said what it needed to).
   */
  async exportProjectBibliography(projectId: string): Promise<BibliographyExportResult | null> {
    const papers = this.plugin.paperService.getInProject(projectId);
    const path = this.bibliographyPath(projectId);
    // Sorting lives in `papersToBibtex` — the caller order of `getInProject`
    // (hydration order) must never leak into the output.
    const body = papersToBibtex(papers);

    const existing = this.plugin.app.vault.getAbstractFileByPath(path);
    if (existing instanceof TFile) {
      const current = await this.plugin.app.vault.cachedRead(existing);
      // Overwrite guard (D36): only files we generated carry the marker —
      // anything else is (or was) hand-written and we never clobber it
      // silently.
      if (!current.includes(BIBTEX_GENERATED_HEADER)) {
        const proceed = await ConfirmModal.ask(this.plugin.app, {
          title: 'Overwrite bibliography',
          message:
            `"${path}" exists and was not generated by ResearchVault.\n\n` +
            'Continuing replaces the whole file; hand edits will be lost.',
          confirmLabel: 'Overwrite',
          destructive: true,
        });
        if (!proceed) return null;
      }
      await this.plugin.app.vault.modify(existing, body);
    } else {
      // The project root may not exist on disk yet (folders are created lazily
      // per the Phase-1 startup-cost fix); create it recursively-ish.
      const parent = normalizePath(path.split('/').slice(0, -1).join('/'));
      if (!this.plugin.app.vault.getAbstractFileByPath(parent)) {
        await this.plugin.app.vault.createFolder(parent).catch(() => {
          /* raced or already created; vault.create errors loudly if it's really missing */
        });
      }
      await this.plugin.app.vault.create(path, body);
    }

    return { path, count: papers.length };
  }
}
