// src/services/citation/bibtex.ts
//
// Hand-rolled, publication-grade BibTeX serializer (3.2 Citation excellence
// C1 / D36). Deliberately dependency-free: the `Paper` shape is small and the
// correct output grammar is ~150 lines. Pure module — no vault, no Obsidian
// imports — so the golden-fixture tests in `tests/bibtex.test.ts` run in
// plain vitest and the same functions back both the `export-bibliography`
// command and the sidebar's "Copy BibTeX entry" action.

import type { Paper, PaperEntryType } from '../../types';

/**
 * First line of every generated bibliography. The export command refuses to
 * overwrite a `.bib` that lacks this marker — a file without it was (probably)
 * hand-written and must not be clobbered silently.
 */
export const BIBTEX_GENERATED_HEADER =
  '% AUTO-GENERATED by ResearchVault -- exports are deterministic; edit the paper notes, not this file.';

/** Entry type the export falls back to when the paper has none (D36). */
const DEFAULT_ENTRY_TYPE: PaperEntryType = 'article';

/**
 * Escape the characters that would break a BibTeX field wrapped in braces:
 * unbalanced braces confuse the parser; `%` starts a comment; `&`, `#`, `_`
 * are special inside table/math contexts that consumers paste into. `$` and
 * `~` are left alone — they are either already TeX or harmless in prose.
 */
export function escapeBibtexValue(value: string): string {
  return value
    .replace(/\\/g, '\\\\') // backslash first, so the escaping below stays literal
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}')
    .replace(/%/g, '\\%')
    .replace(/&/g, '\\&')
    .replace(/#/g, '\\#')
    .replace(/_/g, '\\_');
}

/**
 * Normalise a page range to BibTeX's double-hyphen convention ("123-145" →
 * "123--145"). Already-double-hyphenated and non-numeric input (roman
 * numerals, section refs) is returned untouched.
 */
export function normalizeBibtexPages(value: string): string {
  return value.replace(/(\d)-(\d)/g, '$1--$2');
}

/**
 * `"Last, First and Last, First"` author line. `authors` holds last names;
 * `authorFirstNames` is positionally paired but may be shorter or empty, in
 * which case the bare last name is emitted (matches what CrossRef hands us
 * for org authors).
 */
export function bibtexAuthors(paper: Paper): string | undefined {
  if (paper.authors.length === 0) return undefined;
  const names = paper.authors.map((last, i) => {
    const first = paper.authorFirstNames?.[i]?.trim();
    return first ? `${last}, ${first}` : last;
  });
  return escapeBibtexValue(names.join(' and '));
}

/**
 * Map the shared `venue` field onto the container field each entry type
 * expects. `book` has no container — venue, when present, is a `series`;
 * `misc` gets `howpublished` so preprints/websites keep provenance.
 */
function venueFieldFor(entryType: PaperEntryType): string {
  switch (entryType) {
    case 'article':
      return 'journal';
    case 'inproceedings':
    case 'incollection':
      return 'booktitle';
    case 'book':
      return 'series';
    case 'thesis':
      return 'school';
    case 'misc':
      return 'howpublished';
  }
}

/**
 * Render one entry. Field order is stable and intentionally mirrors the
 * order copy-editors scan them: author, title, year, container, volume,
 * number, pages, publisher, doi, url, keywords, abstract.
 */
export function paperToBibtexEntry(paper: Paper): string {
  const entryType = paper.entryType ?? DEFAULT_ENTRY_TYPE;
  const fields: Array<[string, string]> = [];
  const authors = bibtexAuthors(paper);
  if (authors) fields.push(['author', authors]);
  fields.push(['title', escapeBibtexValue(paper.title)]);
  fields.push(['year', String(paper.year)]);
  if (paper.venue) fields.push([venueFieldFor(entryType), escapeBibtexValue(paper.venue)]);
  if (paper.volume) fields.push(['volume', escapeBibtexValue(paper.volume)]);
  if (paper.issue) fields.push(['number', escapeBibtexValue(paper.issue)]);
  if (paper.pages) fields.push(['pages', normalizeBibtexPages(escapeBibtexValue(paper.pages))]);
  if (paper.publisher) fields.push(['publisher', escapeBibtexValue(paper.publisher)]);
  if (paper.doi) fields.push(['doi', escapeBibtexValue(paper.doi)]);
  if (paper.url) fields.push(['url', escapeBibtexValue(paper.url)]);
  if (paper.keywords.length > 0) fields.push(['keywords', escapeBibtexValue(paper.keywords.join(', '))]);
  if (paper.abstract) fields.push(['abstract', escapeBibtexValue(paper.abstract)]);

  const body = fields.map(([name, value]) => `  ${name} = {${value}}`).join(',\n');
  return `@${entryType}{${paper.citekey},\n${body},\n}`;
}

/**
 * Render a whole bibliography: header marker, then entries sorted by citekey
 * (case-insensitively) so re-exports diff cleanly. Deterministic — same
 * papers in, byte-identical file out.
 */
export function papersToBibtex(papers: Paper[]): string {
  const sorted = [...papers].sort((a, b) =>
    a.citekey.localeCompare(b.citekey, 'en', { sensitivity: 'base' }),
  );
  const entries = sorted.map(paperToBibtexEntry);
  return `${BIBTEX_GENERATED_HEADER}\n\n${entries.join('\n\n')}\n`;
}
