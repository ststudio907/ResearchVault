import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { writeFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	metafile: prod,
});

if (prod) {
	const result = await context.rebuild();
	// Bundle-size report (Phase 4 release hygiene): write the raw metafile for
	// offline inspection (`npx esbuild --analyze` / bundle analyzers) and print
	// a compact text summary of what contributes to main.js.
	if (result.metafile) {
		await writeFile('esbuild-metafile.json', JSON.stringify(result.metafile));
		const report = await esbuild.analyzeMetafile(result.metafile);
		console.log(report);
		console.log('Metafile written to esbuild-metafile.json');
	}
	process.exit(0);
} else {
	await context.watch();
}
