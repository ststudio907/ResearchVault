#!/usr/bin/env python3
"""2.8.Sidebar refactor.

Splits `render()` into `render()` (one-time: header + persistent list
container) and `renderList()` (re-creates only the list children). The
search input lives inside the header, which is never re-created, so it
keeps focus across keystrokes.

Also changes Fuse config in vault-indexer.ts: minMatchCharLength 2 -> 1,
threshold 0.35 -> 0.4, so 1-character queries return hits.
"""
from pathlib import Path
import re

ROOT = Path('src/ui/views/projects-sidebar-view.ts')

src = ROOT.read_text()

# --- 1. Update event-bus subscriptions: only `projectChanged` does a full
# render (so the search input is fresh for the new project). All paper /
# index updates do `renderList()` only. -------------------------------
old_subs = (
    "    this.unsubscribers.push(\n"
    "      this.rv.eventBus.on('paperImported', () => this.render()),\n"
    "      this.rv.eventBus.on('paperUpdated', () => this.render()),\n"
    "      this.rv.eventBus.on('paperRemoved', () => this.render()),\n"
    "      this.rv.eventBus.on('paperStatusChanged', () => this.render()),\n"
    "      this.rv.eventBus.on('projectChanged', () => this.render()),\n"
    "      // Refresh results list when the indexer adds/removes/rebuilds records\n"
    "      // (e.g. a quote was captured while the user is mid-typing a query).\n"
    "      this.rv.eventBus.on('indexUpdated', () => this.render()),\n"
    "    );\n"
)
new_subs = (
    "    // Most updates only need to refresh the paper list — the header (with\n"
    "    // the search input) is rendered once on `onOpen` and stays mounted\n"
    "    // so its focus is never blown away by a re-render. `projectChanged`\n"
    "    // does a full re-render because switching projects should also clear\n"
    "    // any in-flight search query.\n"
    "    this.unsubscribers.push(\n"
    "      this.rv.eventBus.on('paperImported', () => this.renderList()),\n"
    "      this.rv.eventBus.on('paperUpdated', () => this.renderList()),\n"
    "      this.rv.eventBus.on('paperRemoved', () => this.renderList()),\n"
    "      this.rv.eventBus.on('paperStatusChanged', () => this.renderList()),\n"
    "      this.rv.eventBus.on('projectChanged', () => {\n"
    "        this.currentQuery = '';\n"
    "        this.render();\n"
    "      }),\n"
    "      // Refresh results list when the indexer adds/removes/rebuilds records\n"
    "      // (e.g. a quote was captured while the user is mid-typing a query).\n"
    "      this.rv.eventBus.on('indexUpdated', () => this.renderList()),\n"
    "    );\n"
)
assert src.count(old_subs) == 1, f"subscriptions block not found uniquely ({src.count(old_subs)})"
src = src.replace(old_subs, new_subs, 1)

# --- 2. Search-input listener: render() -> renderList() ---------------
