new_search = (
    "      this.searchDebounce = window.setTimeout(() => {\n"
    "        this.searchDebounce = null;\n"
    "        this.renderList();\n"
    "      }, 80);\n"
)
assert src.count(old_search) == 1, f"search listener block not found ({src.count(old_search)})"
src = src.replace(old_search, new_search, 1)

# --- 3. Replace the render() body with the slim header-only version +
# add renderList() right after. --------------------------------------
