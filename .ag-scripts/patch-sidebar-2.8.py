    "      const activePapers = new Set(papers.map((p) => p.id));\n"
    "      const scoped = hits.filter((p) => activePapers.has(p.id));\n"
    "      if (scoped.length === 0) {\n"
    "        listEl.createEl('p', {\n"
    "          text: `No papers match \"${trimmed}\" in this project.`,\n"
    "          cls: 'researchvault-sidebar-empty',\n"
