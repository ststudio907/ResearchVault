    "   */\n"
    "  private render(): void {\n"
    "    const { contentEl } = this;\n"
    "    contentEl.empty();\n"
    "    contentEl.addClass('researchvault-sidebar');\n"
    "\n"
    "    // Header is mounted once per full render. It contains the search\n"
